"""Measure where heads attach: neck tops on seated bodies, the placeholder head on Mr. G. Writes ../anchors.js."""
import json, os
import numpy as np
from PIL import Image

A = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets')


def alpha(name):
    im = Image.open(os.path.join(A, name + '.webp')).convert('RGBA')
    return np.array(im)[:, :, 3] > 60, im.size


def neck(name):
    """Neck top centre on a headless seated body, as fractions of the image (x from left, y from top)."""
    a, (w, h) = alpha(name)
    band = range(int(w * .3), int(w * .7))
    first = {x: (np.argmax(a[:, x]) if a[:, x].any() else h) for x in band}
    top = min(first.values())
    cols = [x for x, y in first.items() if y <= top + h * .04]
    # neck width at a little below its top
    row = a[min(h - 1, int(top + h * .05)), int(w * .3):int(w * .7)]
    xs = np.nonzero(row)[0]
    nw = (xs.max() - xs.min()) / w if len(xs) else .12
    return {'x': round(float(np.mean(cols)) / w, 4), 'y': round(top / h, 4), 'w': round(float(nw), 4), 'ar': round(w / h, 4)}


def mrg_head(name):
    """Bounding box of the small placeholder head at the top of a Mr. G pose."""
    a, (w, h) = alpha(name)
    band = slice(int(w * .25), int(w * .75))
    rows = np.nonzero(a[:, band].any(1))[0]
    y0 = rows[0]
    widths = []
    for y in range(y0, y0 + int(h * .15)):
        xs = np.nonzero(a[y, band])[0]
        widths.append((xs.max() - xs.min()) if len(xs) else 0)
    widths = np.array(widths)
    peak = int(widths[: int(h * .1)].argmax())
    neck_i = peak + int(widths[peak: peak + int(h * .06)].argmin())
    y = y0 + peak
    xs = np.nonzero(a[y, band])[0] + int(w * .25)
    return {'cx': round(float((xs.min() + xs.max()) / 2) / w, 4), 'top': round(y0 / h, 4),
            'chin': round((y0 + neck_i) / h, 4), 'w': round(float(widths[peak]) / w, 4), 'ar': round(w / h, 4)}


out = {
    'bodies': {f'body{s}_{i}': neck(f'body{s}_{i}') for s in 'AB' for i in range(4)},
    'mrg': {n: mrg_head(n) for n in ('mrg_welcome', 'mrg_wave', 'mrg_champagne')},
    'cars': {n: round(Image.open(os.path.join(A, n + '.webp')).width / Image.open(os.path.join(A, n + '.webp')).height, 4)
             for n in ('car_gold', 'car_pink', 'car_white')},
}
with open(os.path.join(A, '..', 'anchors.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/anchors.py: head attachment points measured from the art.\nwindow.ANCHORS = ' + json.dumps(out, indent=1) + ';\n')
print(json.dumps(out, indent=1))
